export type MessageVariables = Record<string, string | number>;

export function isLocale(value: unknown): value is Locale {
  return value === 'en' || value === 'ru';
}

export function normalizeLocale(value: unknown): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

export function translateMessage(locale: Locale, key: MessageKey, variables?: MessageVariables): string {
  const template = (locale === 'ru' ? RU_MESSAGES[key] : undefined) ?? EN_MESSAGES[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, variable: string) => {
    const value = variables?.[variable];
    return value === undefined ? match : String(value);
  });
}
